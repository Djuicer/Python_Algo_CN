"""
Project Euler Problem 301: https://projecteuler.net/problem=301

题目说明：
Nim 是一种石堆游戏，两名玩家轮流从任意一堆中移除任意数量的石子，直到没有石子剩余。

考虑 Nim 的三堆常规玩法，规则如下：
- 游戏开始时有三堆石子。
- 每名玩家在自己的回合中，可以从任意一堆中移除任意正数个石子。
- 首个无法行动（因为没有石子剩余）的玩家失败。

若 (n1, n2, n3) 表示由大小为 n1、n2 和 n3 的石堆组成的 Nim 局面，
则存在一个可以查阅或自行推导的简单函数 X(n1, n2, n3)，其返回值为：
- 若采用完美策略时即将行动的玩家最终会失败，则返回零；
- 若采用完美策略时即将行动的玩家最终会获胜，则返回非零值。

例如，X(1,2,3) = 0，因为无论当前玩家如何行动，对手都可以通过一次行动留下两堆
大小相等的石子。此后，对手可以镜像当前玩家的每次行动，直到没有石子剩余，
因此当前玩家失败。示例如下：
- 当前玩家移动到 (1,2,1)
- 对手移动到 (1,0,1)
- 当前玩家移动到 (0,0,1)
- 对手移动到 (0,0,0)，从而获胜。

有多少个正整数 n <= 2^30 满足 X(n,2n,3n) = 0？
"""


def solution(exponent: int = 30) -> int:
    """
    对于任意给定指数 x >= 0，1 <= n <= 2^x。
    当每局 Nim 游戏都有形如 (n, 2*n, 3*n) 的三堆石子时，返回失败局面的数量。
    >>> solution(0)
    1
    >>> solution(2)
    3
    >>> solution(10)
    144
    """
    # 要求给定指数 x 下失败局面的总数，需要计算斐波那契数 F(x+2)
    fibonacci_index = exponent + 2
    phi = (1 + 5**0.5) / 2
    fibonacci = (phi**fibonacci_index - (phi - 1) ** fibonacci_index) / 5**0.5

    return int(fibonacci)


